// Generates supabase/migrations/20261025000001_fan_quest_seed.sql from scripts/catalog.mjs.
// Usage: node scripts/build-seed.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { ITEMS, BOXES, DUPLICATE_REFUND, MISSIONS, CHALLENGES, ACHIEVEMENTS, TRIVIA, SLOTS, RARITIES } from './catalog.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const errors = [];

// ---- validation ----
const ids = new Set();
ITEMS.forEach((it, i) => {
  if (ids.has(it.id)) errors.push(`duplicate item id ${it.id}`);
  ids.add(it.id);
  if (!SLOTS.includes(it.slot)) errors.push(`${it.id}: bad slot ${it.slot}`);
  if (!RARITIES.includes(it.rarity)) errors.push(`${it.id}: bad rarity`);
  if (it.starter && (it.price || it.boxes.length)) errors.push(`${it.id}: starter items cannot be sold or boxed`);
  if (!it.starter && !it.price && !it.boxes.length) errors.push(`${it.id}: unobtainable (no price, no box)`);
  it.boxes.forEach(b => { if (!BOXES.some(x => x.id === b)) errors.push(`${it.id}: unknown box ${b}`); });
  it.sort = i;
});
for (const b of BOXES) {
  const total = Object.values(b.odds).reduce((a, x) => a + x, 0);
  if (total !== 100) errors.push(`box ${b.id}: odds must total 100 (got ${total})`);
  for (const r of Object.keys(b.odds)) {
    const n = ITEMS.filter(i => i.boxes.includes(b.id) && i.rarity === r).length;
    if (!n) errors.push(`box ${b.id}: no ${r} items in pool`);
  }
}
for (const s of ['species', 'hair', 'background', 'pose', 'frame']) {
  if (!ITEMS.some(i => i.slot === s && i.starter)) errors.push(`slot ${s} needs a starter item`);
}
TRIVIA.forEach((q, i) => {
  if (q[3].length !== 4 || q[4].length !== 4 || q[5] < 0 || q[5] > 3) errors.push(`trivia ${i}: needs 4 choices`);
});
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

// ---- SQL ----
const lit = v => '$fqjson$' + JSON.stringify(v) + '$fqjson$::jsonb';
const items = ITEMS.map(({ id, slot, name, name_zh, rarity, price, starter, boxes, art, sort }) =>
  ({ id, slot, name, name_zh, rarity, price, starter, boxes, art, sort }));
const boxes = BOXES.map(b => ({ ...b, duplicate_refund: DUPLICATE_REFUND }));
const achievements = ACHIEVEMENTS.map((a, i) => ({ ...a, sort: i }));
const trivia = TRIVIA.map((q, i) => ({ id: i + 1, level: q[0], question: q[1], question_zh: q[2], choices: q[3], choices_zh: q[4], answer: q[5] }));

const sql = `-- =====================================================================
-- Fan Quest Studio — catalogue seed. GENERATED by scripts/build-seed.mjs
-- from scripts/catalog.mjs. Do not edit by hand; edit the catalogue and
-- re-run the generator. Safe to re-run (upserts; removed rows are
-- deactivated, never deleted, so existing inventories stay valid).
-- =====================================================================

insert into public.fq_items (id, slot, name, name_zh, rarity, price, starter, boxes, art, sort, active)
select x.id, x.slot, x.name, x.name_zh, x.rarity, x.price, x.starter, x.boxes, x.art, x.sort, true
  from jsonb_to_recordset(${lit(items)})
    as x(id text, slot text, name text, name_zh text, rarity text, price integer, starter boolean, boxes text[], art jsonb, sort integer)
on conflict (id) do update set slot = excluded.slot, name = excluded.name, name_zh = excluded.name_zh, rarity = excluded.rarity,
  price = excluded.price, starter = excluded.starter, boxes = excluded.boxes, art = excluded.art, sort = excluded.sort, active = true;
update public.fq_items set active = false where id not in (select jsonb_array_elements_text(${lit(items.map(i => i.id))}));

insert into public.fq_boxes (id, name, name_zh, description, description_zh, cost, odds, duplicate_refund, sort, active)
select x.id, x.name, x.name_zh, x.description, x.description_zh, x.cost, x.odds, x.duplicate_refund, x.sort, true
  from jsonb_to_recordset(${lit(boxes)})
    as x(id text, name text, name_zh text, description text, description_zh text, cost integer, odds jsonb, duplicate_refund jsonb, sort integer)
on conflict (id) do update set name = excluded.name, name_zh = excluded.name_zh, description = excluded.description,
  description_zh = excluded.description_zh, cost = excluded.cost, odds = excluded.odds, duplicate_refund = excluded.duplicate_refund,
  sort = excluded.sort, active = true;
update public.fq_boxes set active = false where id not in (select jsonb_array_elements_text(${lit(boxes.map(b => b.id))}));

insert into public.fq_missions (id, title, title_zh, event, target, reward, active)
select x.id, x.title, x.title_zh, x.event, x.target, x.reward, true
  from jsonb_to_recordset(${lit(MISSIONS)}) as x(id text, title text, title_zh text, event text, target integer, reward integer)
on conflict (id) do update set title = excluded.title, title_zh = excluded.title_zh, event = excluded.event,
  target = excluded.target, reward = excluded.reward, active = true;
update public.fq_missions set active = false where id not in (select jsonb_array_elements_text(${lit(MISSIONS.map(m => m.id))}));

insert into public.fq_challenges (id, game, difficulty, metric, target, reward, title, title_zh, active)
select x.id, x.game, x.difficulty, x.metric, x.target, x.reward, x.title, x.title_zh, true
  from jsonb_to_recordset(${lit(CHALLENGES)})
    as x(id text, game text, difficulty text, metric text, target integer, reward integer, title text, title_zh text)
on conflict (id) do update set game = excluded.game, difficulty = excluded.difficulty, metric = excluded.metric,
  target = excluded.target, reward = excluded.reward, title = excluded.title, title_zh = excluded.title_zh, active = true;
update public.fq_challenges set active = false where id not in (select jsonb_array_elements_text(${lit(CHALLENGES.map(c => c.id))}));

insert into public.fq_achievements (id, icon, metric, target, reward, title, title_zh, description, description_zh, sort, active)
select x.id, x.icon, x.metric, x.target, x.reward, x.title, x.title_zh, x.description, x.description_zh, x.sort, true
  from jsonb_to_recordset(${lit(achievements)})
    as x(id text, icon text, metric text, target integer, reward integer, title text, title_zh text, description text, description_zh text, sort integer)
on conflict (id) do update set icon = excluded.icon, metric = excluded.metric, target = excluded.target, reward = excluded.reward,
  title = excluded.title, title_zh = excluded.title_zh, description = excluded.description, description_zh = excluded.description_zh,
  sort = excluded.sort, active = true;
update public.fq_achievements set active = false where id not in (select jsonb_array_elements_text(${lit(achievements.map(a => a.id))}));

insert into fq_private.trivia (id, level, question, question_zh, choices, choices_zh, answer, active)
select x.id, x.level, x.question, x.question_zh, x.choices, x.choices_zh, x.answer, true
  from jsonb_to_recordset(${lit(trivia)})
    as x(id integer, level text, question text, question_zh text, choices jsonb, choices_zh jsonb, answer integer)
on conflict (id) do update set level = excluded.level, question = excluded.question, question_zh = excluded.question_zh,
  choices = excluded.choices, choices_zh = excluded.choices_zh, answer = excluded.answer, active = true;
update fq_private.trivia set active = false where id > ${trivia.length};

-- Carry over v1 prototype inventory (item keys match v2 item ids).
do $$ begin
  if to_regclass('public.fq_v1_inventory') is not null then
    insert into public.fq_inventory (user_id, item_id, source, acquired_at)
    select v.user_id, v.item_key, 'migration', v.created_at
      from public.fq_v1_inventory v join public.fq_items i on i.id = v.item_key
      join public.fq_profiles p on p.user_id = v.user_id
    on conflict do nothing;
  end if;
end $$;
`;
const out = join(root, 'supabase/migrations/20261025000001_fan_quest_seed.sql');
writeFileSync(out, sql);
console.log(`wrote ${out}: ${items.length} items, ${boxes.length} boxes, ${MISSIONS.length} missions, ${CHALLENGES.length} challenges, ${achievements.length} achievements, ${trivia.length} trivia`);
