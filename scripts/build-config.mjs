// Build step for static hosting (Netlify, etc.):
//  1. writes config.js from the SUPABASE_URL / SUPABASE_ANON_KEY environment variables
//  2. copies only the files the browser needs into dist/
// Usage: SUPABASE_URL=... SUPABASE_ANON_KEY=... node scripts/build-config.mjs
import { writeFileSync, mkdirSync, cpSync, rmSync, existsSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Allow a local .env for convenience (never committed).
if (existsSync(join(root, '.env'))) {
  for (const line of readFileSync(join(root, '.env'), 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const url = process.env.SUPABASE_URL, key = process.env.SUPABASE_ANON_KEY;
if (!url || !key) { console.error('Set SUPABASE_URL and SUPABASE_ANON_KEY (public anon/publishable key).'); process.exit(1); }
if (/service_role/.test(key) || (() => { try { return JSON.parse(Buffer.from(key.split('.')[1], 'base64url')).role === 'service_role'; } catch { return false; } })()) {
  console.error('Refusing to build: SUPABASE_ANON_KEY looks like a service_role key. Use the anon/publishable key.'); process.exit(1);
}
const cfg = `/* Generated by scripts/build-config.mjs — public browser config only. */\nwindow.FAN_QUEST_CONFIG = ${JSON.stringify({ supabaseUrl: url, supabaseAnonKey: key }, null, 2)};\n`;
const dist = join(root, 'dist');
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
for (const f of ['index.html', 'manifest.json', 'icon-512.png', '.nojekyll', 'css', 'js', 'assets', 'vendor']) {
  if (existsSync(join(root, f))) cpSync(join(root, f), join(dist, f), { recursive: true });
}
writeFileSync(join(dist, 'config.js'), cfg);
console.log(`Built dist/ for ${url}`);
